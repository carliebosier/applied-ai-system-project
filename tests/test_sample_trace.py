"""Tests for docs/sample_trace.log, the committed mock-run trace (plan §9 increment 12).

Read-only: the file is generated by two agent_demo.py --mock runs (fixtures 2 and 3) and is
never rewritten here. No network. Task id and run id values are never asserted.
"""

import json
import re
from pathlib import Path

TRACE_PATH = Path(__file__).resolve().parent.parent / "docs" / "sample_trace.log"
LINE = re.compile(r"^run=([0-9a-f]{8}) step=([a-z_]+) (\{.*\})$")

ALL_STEPS = [
    "request",
    "parse_output",
    "validation",
    "plan",
    "revision_proposal",
    "revision_validation",
    "revised_plan",
    "stop",
    "approval",
]
RUN1_STEPS = ALL_STEPS
RUN2_STEPS = ["request", "parse_output", "validation", "plan", "stop", "approval"]


def _text() -> str:
    return TRACE_PATH.read_text(encoding="utf-8")


def _entries() -> list[tuple[str, str, dict]]:
    """(run_id, step, payload) for every non-empty line, in file order."""
    entries = []
    for line in _text().splitlines():
        if not line.strip():
            continue
        match = LINE.match(line)
        assert match, f"malformed line: {line!r}"
        entries.append((match.group(1), match.group(2), json.loads(match.group(3))))
    return entries


def _runs() -> list[list[tuple[str, dict]]]:
    """Entries grouped by run id, in order of first appearance."""
    runs: dict[str, list[tuple[str, dict]]] = {}
    for run_id, step, payload in _entries():
        runs.setdefault(run_id, []).append((step, payload))
    return list(runs.values())


def _payload(run: list[tuple[str, dict]], step: str) -> dict:
    matches = [payload for name, payload in run if name == step]
    assert len(matches) == 1, f"expected one {step!r} step, got {len(matches)}"
    return matches[0]


def test_every_line_has_the_log_format_and_valid_json():
    entries = _entries()
    assert entries
    for _run_id, _step, payload in entries:
        assert isinstance(payload, dict)


def test_exactly_two_runs():
    assert len({run_id for run_id, _step, _payload in _entries()}) == 2


def test_run_1_is_the_conflict_fix_ending_clean():
    run = _runs()[0]
    assert [step for step, _payload in run] == RUN1_STEPS
    stop = _payload(run, "stop")
    assert stop["stop_reason"] == "clean"
    assert stop["revise_calls"] == 1
    assert _payload(run, "approval")["decision"] == "approve_revised"


def test_run_2_is_the_over_budget_run_with_no_revise_call():
    run = _runs()[1]
    assert [step for step, _payload in run] == RUN2_STEPS
    stop = _payload(run, "stop")
    assert stop["stop_reason"] == "no_movable_conflicts"
    assert stop["revise_calls"] == 0
    assert _payload(run, "approval")["decision"] == "approve_original"


def test_every_step_name_appears():
    steps = {step for _run_id, step, _payload in _entries()}
    for step in ALL_STEPS:
        assert step in steps, f"missing step {step!r}"


def test_no_secrets_or_tracebacks():
    text = _text()
    assert "GEMINI" not in text
    assert "api_key" not in text.lower()
    assert "Traceback" not in text
